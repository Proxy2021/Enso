var focusId = (params.focusId || "").trim();
var format = (params.format || "markdown").trim();

if (!focusId) {
  return { content: [{ type: "text", text: JSON.stringify({
    tool: "enso_sprint_results_share",
    success: false,
    error: "Missing focusId parameter"
  }) }] };
}

var homeDir = process.env.HOME || process.env.USERPROFILE || "~";
var focusPath = homeDir + "/.enso/data/focus-areas.json";

// Load focus state
var targetArea = null;
try {
  var focusResult = await ctx.readFile(focusPath);
  var focusData = null;
  if (focusResult && typeof focusResult === "string") {
    focusData = JSON.parse(focusResult);
  } else if (focusResult && focusResult.success && focusResult.data) {
    focusData = typeof focusResult.data === "string" ? JSON.parse(focusResult.data) : focusResult.data;
  }

  if (focusData && focusData.areas) {
    for (var ai = 0; ai < focusData.areas.length; ai++) {
      if (focusData.areas[ai].id === focusId) {
        targetArea = focusData.areas[ai];
        break;
      }
    }
  }
} catch(e) {}

if (!targetArea) {
  return { content: [{ type: "text", text: JSON.stringify({
    tool: "enso_sprint_results_share",
    success: false,
    error: "Focus area not found: " + focusId
  }) }] };
}

var title = targetArea.title || "Untitled";
var summary = targetArea.lastSprintSummary;
var sprintDate = targetArea.lastSprintDate ? new Date(targetArea.lastSprintDate).toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" }) : "Unknown";
var cycleCount = targetArea.cycleCount || 0;

var shareText = "";

if (format === "markdown") {
  shareText = "# Sprint Results: " + title + "\n\n";
  shareText += "**Date:** " + sprintDate + " | **Cycle:** #" + cycleCount + "\n\n";

  if (summary) {
    shareText += "## Summary\n" + (summary.sprintSummary || "") + "\n\n";

    if (summary.deliverables && summary.deliverables.length > 0) {
      shareText += "## Deliverables\n";
      for (var di = 0; di < summary.deliverables.length; di++) {
        var del = summary.deliverables[di];
        var typeLabel = (del.entityType || "synthesis").charAt(0).toUpperCase() + (del.entityType || "synthesis").slice(1);
        shareText += (di + 1) + ". **" + (del.taskTitle || "Untitled") + "** (" + typeLabel + ")\n";
        shareText += "   - " + (del.howItHelps || "") + "\n";
        shareText += "   - Quick start: " + (del.quickStart || "") + "\n\n";
      }
    }

    if (summary.recommendedFirstAction) {
      var recIdx = summary.recommendedFirstAction.deliverableIndex || 0;
      var recDel = summary.deliverables && summary.deliverables[recIdx];
      if (recDel) {
        shareText += "## Recommended First Action\n";
        shareText += "Start with **" + recDel.taskTitle + "** — " + (summary.recommendedFirstAction.reason || "") + "\n\n";
      }
    }

    if (summary.nextSteps && summary.nextSteps.length > 0) {
      shareText += "## Next Steps\n";
      for (var ni = 0; ni < summary.nextSteps.length; ni++) {
        shareText += "- " + summary.nextSteps[ni] + "\n";
      }
      shareText += "\n";
    }
  } else if (targetArea.lastSprintResults) {
    shareText += "## Results\n" + targetArea.lastSprintResults + "\n\n";
  }

  shareText += "---\n*Generated by Enso Sprint Results Dashboard*";
} else {
  // Plain text format
  shareText = "SPRINT RESULTS: " + title + "\n";
  shareText += "Date: " + sprintDate + " | Cycle: #" + cycleCount + "\n\n";

  if (summary) {
    shareText += summary.sprintSummary + "\n\n";
    if (summary.deliverables) {
      shareText += "DELIVERABLES:\n";
      for (var ti = 0; ti < summary.deliverables.length; ti++) {
        var td = summary.deliverables[ti];
        shareText += (ti + 1) + ". " + td.taskTitle + " [" + td.entityType + "]\n";
        shareText += "   " + td.howItHelps + "\n\n";
      }
    }
  }
}

var result = {
  tool: "enso_sprint_results_share",
  success: true,
  focusId: focusId,
  focusTitle: title,
  format: format,
  shareText: shareText,
  message: "Shareable summary generated"
};

return { content: [{ type: "text", text: JSON.stringify(result) }] };
